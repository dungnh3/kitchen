// durationCode writes d as Go code, for example 5 * time.Minute.
func durationCode(d time.Duration) string {
	for _, u := range []struct {
		d    time.Duration
		name string
	}{{time.Hour, "time.Hour"}, {time.Minute, "time.Minute"}, {time.Second, "time.Second"}, {time.Millisecond, "time.Millisecond"}} {
		if d%u.d == 0 {
			if d == u.d {
				return u.name
			}
			return strconv.FormatInt(int64(d/u.d), 10) + " * " + u.name
		}
	}
	return "time.Duration(" + strconv.FormatInt(int64(d), 10) + ")"
}

