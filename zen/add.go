const addUsage = `Usage:
  zen add domain <name> [flags]    a CRUD resource: proto service, store, migration, tests
  zen add consumer <name> [flags]  a pubsub consumer in the worker (-with pubsub)
  zen add job <name> [flags]       a periodic job in the worker (-with lease)
  zen add task <name> [flags]      a background task in the jobs table (-with jobs)
  zen add client <service>         a gRPC client of another service (grpcx)
  zen add webhook <name>           a receiver of a signed webhook (webhook)

Run in a service generated by "zen new service"; <name> is lower-case
words separated by dashes. Run "zen add <kind> -h" for the flags.
`

// addCommand runs "zen add <kind> <name>".
func addCommand(ctx context.Context, args []string, stdout, stderr io.Writer) error {
	if len(args) == 0 {
		_, _ = fmt.Fprint(stderr, addUsage)
		return errUsage
	}
	kind, args := args[0], args[1:]
	fs := flag.NewFlagSet("zen add "+kind, flag.ContinueOnError)
	fs.SetOutput(stderr)
	dir := fs.String("dir", ".", "project directory")
	var (
		plural     *string
		noGenerate *bool
		every      *time.Duration
	)
	switch kind {
	case "domain":
		plural = fs.String("plural", "", "plural of the name when it is not the regular English plural, for example people")
		noGenerate = fs.Bool("no-generate", false, "do not run buf generate and sqlc generate")
	case "consumer", "client", "webhook":
	case "job":
		every = fs.Duration("every", time.Minute, "time between two runs")
	case "task":
		every = fs.Duration("every", 0, "also run the task on a schedule: the time between two runs, at least 1s (0: only when enqueued)")
	default:
		_, _ = fmt.Fprint(stderr, addUsage)
		return errUsage
	}
	// The name may come before or after the flags.
	var name string
	if len(args) > 0 && !strings.HasPrefix(args[0], "-") {
		name, args = args[0], args[1:]
	}
	if err := fs.Parse(args); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return err
		}
		return errUsage
	}
	if name == "" && fs.NArg() > 0 {
		name = fs.Arg(0)
	} else if fs.NArg() > 0 {
		_, _ = fmt.Fprintf(stderr, "unexpected arguments: %v\n", fs.Args())
		return errUsage
	}
	if name == "" {
		_, _ = fmt.Fprintf(stderr, "zen add %s: missing <name>\n", kind)
		return errUsage
	}

	root, err := os.OpenRoot(*dir)
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()
	m, err := readManifest(root)
	if err != nil {
		return err
	}
	p := m.Answers.params()
	p.applyDefaults()

	var c *change
	switch kind {
	case "domain":
		c, err = addDomain(root, p, name, *plural)
	case "consumer":
		c, err = addConsumer(root, p, name)
	case "job":
		c, err = addJob(root, p, name, *every)
	case "client":
		c, err = addClient(root, p, name)
	case "task":
		c, err = addTask(root, p, name, *every)
	case "webhook":
		c, err = addWebhook(root, p, name)
	}
	if err != nil {
		return err
	}
	if err := c.apply(root); err != nil {
		return err
	}
	_, _ = fmt.Fprintf(stdout, "Added %s %s:\n", kind, name)
	for _, rel := range c.paths() {
		_, _ = fmt.Fprintf(stdout, "  %s\n", rel)
	}
	if kind == "domain" {
		manual := "  make generate\n"
		if *noGenerate {
			_, _ = fmt.Fprintf(stdout, "\nNext steps:\n%s  make test\n", manual)
			return nil
		}
		_, _ = fmt.Fprintln(stdout, "Generating code...")
		if err := generateDomain(ctx, *dir, nil, p.SQL(), stdout, stderr); err != nil {
			return fmt.Errorf("%w\nThe files are written; finish by hand:\n%s", err, manual)
		}
	}
	_, _ = fmt.Fprintln(stdout, "\nNext steps:\n  make test")
	return nil
}

// generateDomain runs the code generators after a new domain.
// env, when non-nil, replaces the environment of the commands.
func generateDomain(ctx context.Context, dir string, env []string, sql bool, stdout, stderr io.Writer) error {
	steps := [][]string{{"go", "run", "github.com/bufbuild/buf/cmd/buf@" + serviceVersions.Buf, "generate"}}
	if sql {
		steps = append(steps, []string{"go", "run", "github.com/sqlc-dev/sqlc/cmd/sqlc@" + serviceVersions.Sqlc, "generate"})
	}
	for _, s := range steps {
		_, _ = fmt.Fprintf(stdout, "  %s\n", strings.Join(s, " "))
		cmd := exec.CommandContext(ctx, s[0], s[1:]...) //nolint:gosec // fixed commands
		cmd.Dir = dir
		cmd.Env = env
		cmd.Stdout, cmd.Stderr = stdout, stderr
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("%s: %w", strings.Join(s, " "), err)
		}
	}
	return nil
}

// change is a set of new files and insertions before marker lines. It is
// computed in full before anything is written.
type change struct {
	files   scaffold.Files
	inserts []insertion
	// once are insertions made only when the file does not hold the text
	// yet, such as an import that several additions need. They are made
	// before inserts.
	once []insertion
}

// insertion puts text on the lines before the line that holds marker,
// indented like it.
type insertion struct {
	path, marker, text string
}

// errMarker is returned when a file lacks the marker line that zen add
// inserts before.
var errMarker = errors.New("marker not found")

func (c *change) paths() []string {
	seen := map[string]bool{}
	for rel := range c.files {
		seen[rel] = true
	}
	for _, in := range append(slices.Clone(c.once), c.inserts...) {
		seen[in.path] = true
	}
	out := make([]string, 0, len(seen))
	for rel := range seen {
		out = append(out, rel)
	}
	slices.Sort(out)
	return out
}

// apply checks every new file and marker, then writes. Nothing is written
// when a check fails.
func (c *change) apply(root *os.Root) error {
	for _, rel := range c.files.Paths() {
		if _, err := root.Stat(filepath.FromSlash(rel)); err == nil {
			return fmt.Errorf("%s already exists", rel)
		} else if !errors.Is(err, fs.ErrNotExist) {
			return err
		}
	}
	edited := map[string][]byte{}
	all := append(slices.Clone(c.once), c.inserts...)
	for i, in := range all {
		b, ok := edited[in.path]
		if !ok {
			var err error
			if b, err = root.ReadFile(filepath.FromSlash(in.path)); err != nil {
				return err
			}
		}
		if i < len(c.once) && bytes.Contains(b, []byte(in.text)) {
			edited[in.path] = b
			continue
		}
		out, err := insertBefore(b, in.marker, in.text)
		if err != nil {
			return fmt.Errorf("%s: %w: add the change by hand", in.path, err)
		}
		edited[in.path] = out
	}
	for rel, b := range edited {
		if path.Ext(rel) == ".go" {
			f, err := format.Source(b)
			if err != nil {
				return fmt.Errorf("%s: %w", rel, err)
			}
			edited[rel] = f
		}
	}
	for _, rel := range c.files.Paths() {
		if err := writeFile(root, rel, c.files[rel]); err != nil {
			return err
		}
	}
	for rel, b := range edited {
		if err := writeFile(root, rel, b); err != nil {
			return err
		}
	}
	return nil
}

// insertBefore inserts text before the only line of b whose trimmed content
// is the marker comment ("// zen:x", "# zen:x" or
// "<!-- zen:x -->").
func insertBefore(b []byte, marker, text string) ([]byte, error) {
	lines := strings.SplitAfter(string(b), "\n")
	at := -1
	for i, l := range lines {
		t := strings.TrimSpace(l)
		if t == "// "+marker || t == "# "+marker || t == "<!-- "+marker+" -->" {
			if at >= 0 {
				return nil, fmt.Errorf("marker %q appears twice", marker)
			}
			at = i
		}
	}
	if at < 0 {
		return nil, fmt.Errorf("%w: %q", errMarker, marker)
	}
	indent := lines[at][:len(lines[at])-len(strings.TrimLeft(lines[at], " \t"))]
	var add strings.Builder
	for l := range strings.SplitSeq(strings.TrimSuffix(text, "\n"), "\n") {
		if l != "" {
			add.WriteString(indent)
		}
		add.WriteString(l + "\n")
	}
	var out bytes.Buffer
	for i, l := range lines {
		if i == at {
			out.WriteString(add.String())
		}
		out.WriteString(l)
	}
	return out.Bytes(), nil
}

// addData is the data of templates/add.
type addData struct {
	Module string
	N      entity
	// Every is the job interval as Go code, EveryText as text.
	Every, EveryText string
	// Env is the prefix of a client's or a webhook's variables, for example
	// BILLING_.
	Env string
	// Redis reports whether the service has a Redis client.
	Redis bool
}

func renderAdd(kind string, d addData) (scaffold.Files, error) {
	files, err := scaffold.Render(templatesFS, "templates/add/"+kind, d)
	if err != nil {
		return nil, err
	}
	out := scaffold.Files{}
	for rel, b := range files {
		out[strings.ReplaceAll(rel, "_name_", d.N.Snake)] = b
	}
	return out, nil
}

func addDomain(root *os.Root, p serviceParams, name, plural string) (*change, error) {
	e, err := newEntity(name, plural)
	if err != nil {
		return nil, err
	}
	version := ""
	if p.SQL() {
		if version, err = nextMigration(root); err != nil {
			return nil, err
		}
	}
	files, err := renderDomain(p, e, version, false)
	if err != nil {
		return nil, err
	}
	newStore := "memstore.New" + e.Names + "()"
	switch {
	case p.Postgres():
		newStore = "pgstore.New" + e.Names + "(d.pool)"
	case p.MySQL():
		newStore = "mysqlstore.New" + e.Names + "(d.db)"
	}
	return &change{files: files, inserts: []insertion{
		{"internal/app/app.go", "zen:stores", e.Camels + " := " + newStore},
		{"internal/app/app.go", "zen:services", "service.New" + e.Name + "Service(" + e.Camels + "),"},
	}}, nil
}

// nextMigration returns the version prefix after the highest one in
// migrations/.
func nextMigration(root *os.Root) (string, error) {
	f, err := root.Open("migrations")
	if err != nil {
		return "", err
	}
	defer func() { _ = f.Close() }()
	entries, err := f.ReadDir(-1)
	if err != nil {
		return "", err
	}
	highest := 0
	for _, e := range entries {
		digits, _, ok := strings.Cut(e.Name(), "_")
		if n, err := strconv.Atoi(digits); ok && err == nil && strings.HasSuffix(e.Name(), ".sql") {
			highest = max(highest, n)
		}
	}
	return fmt.Sprintf("%05d", highest+1), nil
}

// reservedConsumer and reservedJob are names whose Go identifiers already
// exist in the package that the new code goes to.
var (
	reservedConsumer = []string{"Items", "Project", "Ordered", "MaxDeliveryAttempts", "Brokers", "TLS", "Concurrency", "Subscription"}
	reservedJob      = []string{"Job", "Run", "Heartbeat"}
)

func addConsumer(_ *os.Root, p serviceParams, name string) (*change, error) {
	if !p.PubSub() {
		return nil, errors.New("zen add consumer needs a service generated with -with pubsub")
	}
	n, err := newName(name)
	if err != nil {
		return nil, err
	}
	if slices.Contains(reservedConsumer, n.Name) {
		return nil, fmt.Errorf("consumer %q: the name %s is taken; choose another", name, n.Name)
	}
	files, err := renderAdd("consumer", addData{Module: p.Module, N: n})
	if err != nil {
		return nil, err
	}
	env := "PUBSUB_" + strings.ToUpper(n.Snake) + "_"
	sub := p.Name + "-" + name + "-worker"
	field := "cfg.PubSub." + n.Name

	subArg := field + ".Subscription"
	test := `Topic: "` + name + `", Subscription: "` + sub + `"`
	envs := `"` + env + `TOPIC": "` + name + `",` + "\n" + `"` + env + `SUBSCRIPTION": "` + sub + `",`
	rows := "| `" + env + "TOPIC` | (required) | Topic of the " + n.Words + " consumer |\n"
	var local string
	switch {
	case p.GCP():
		rows += "| `" + env + "SUBSCRIPTION` | (required) | Its subscription |\n"
		local = "LOCAL_ENV += " + env + "TOPIC=" + name + " " + env + "SUBSCRIPTION=" + sub + "\n" +
			"LOCAL_SUBSCRIPTIONS += " + name + ":" + sub
	case p.Kafka():
		subArg += ", " + field + ".DeadLetterTopic"
		test += `, DeadLetterTopic: "` + name + `.dlq"`
		envs += "\n" + `"` + env + `DEAD_LETTER_TOPIC": "` + name + `.dlq",`
		rows += "| `" + env + "SUBSCRIPTION` | (required) | Its consumer group |\n" +
			"| `" + env + "DEAD_LETTER_TOPIC` | (required) | Its dead-letter topic |\n"
		local = "LOCAL_ENV += " + env + "TOPIC=" + name + " " + env + "SUBSCRIPTION=" + sub + " " + env + "DEAD_LETTER_TOPIC=" + name + ".dlq\n" +
			"LOCAL_TOPICS += " + name + " " + name + ".dlq"
	case p.SQS():
		subArg = `""`
		test = `Topic: "` + name + `"`
		envs = `"` + env + `TOPIC": "http://localhost:9324/000000000000/` + name + `",`
		rows = "| `" + env + "TOPIC` | (required) | URL of the queue of the " + n.Words + " consumer |\n"
		local = "LOCAL_ENV += " + env + "TOPIC=$(SQS_URL)/" + name + "\n" +
			"LOCAL_QUEUES += " + name
	}
	return &change{files: files, inserts: []insertion{
		{"internal/config/config.go", "zen:subscriptions", n.Name + " Subscription `envPrefix:\"" + strings.ToUpper(n.Snake) + "_\"`"},
		{"internal/config/config.go", "zen:subscriptions-validate", `errs = append(errs, c.PubSub.` + n.Name + `.Validate("` + env + `"))`},
		{"internal/config/config_test.go", "zen:subscriptions-env", envs},
		{"internal/app/worker.go", "zen:consumers", "if err := subscribe(" + field + ".Topic, " + subArg + ", consumer.New" + n.Name + "(logger).Handler()); err != nil {\n" +
			"\treturn fmt.Errorf(\"" + name + " consumer: %w\", err)\n}"},
		{"internal/app/app_test.go", "zen:subscriptions-test", n.Name + ": config.Subscription{" + test + "},"},
		{"docs/ENV.md", "zen:subscriptions", strings.TrimSuffix(rows, "\n")},
		{"Makefile", "zen:local-env", local},
	}}, nil
}

func addJob(_ *os.Root, p serviceParams, name string, every time.Duration) (*change, error) {
	if !p.Lease() {
		return nil, errors.New("zen add job needs a service generated with -with lease")
	}
	if every <= 0 {
		return nil, fmt.Errorf("-every %v: want a positive duration", every)
	}
	n, err := newName(name)
	if err != nil {
		return nil, err
	}
	if slices.Contains(reservedJob, n.Name) {
		return nil, fmt.Errorf("job %q: the name %s is taken; choose another", name, n.Name)
	}
	files, err := renderAdd("job", addData{Module: p.Module, N: n, Every: durationCode(every), EveryText: every.String()})
	if err != nil {
		return nil, err
	}
	return &change{files: files, inserts: []insertion{
		{"internal/app/worker.go", "zen:jobs", "job." + n.Name + "(logger),"},
	}}, nil
}

// reservedTask are names whose Go identifiers already exist in package task.
var reservedTask = []string{"Heartbeat", "Register", "Periodic"}

func addTask(_ *os.Root, p serviceParams, name string, every time.Duration) (*change, error) {
	if !p.Jobs() {
		return nil, errors.New("zen add task needs a service generated with -with jobs")
	}
	if every < 0 || every > 0 && every < time.Second {
		return nil, fmt.Errorf("-every %v: want 0 (no schedule) or at least 1s", every)
	}
	n, err := newName(name)
	if err != nil {
		return nil, err
	}
	// The new code declares Register<Name>, <Name>Every and <name>Worker.
	if slices.Contains(reservedTask, n.Name) || strings.HasPrefix(n.Name, "Register") || strings.HasSuffix(n.Name, "Every") || strings.HasSuffix(n.Name, "Worker") {
		return nil, fmt.Errorf("task %q: the name %s is taken or clashes with the names zen generates; choose another", name, n.Name)
	}
	d := addData{Module: p.Module, N: n}
	if every > 0 {
		d.Every, d.EveryText = durationCode(every), every.String()
	}
	files, err := renderAdd("task", d)
	if err != nil {
		return nil, err
	}
	c := &change{files: files, inserts: []insertion{
		{"internal/task/task.go", "zen:tasks", "Register" + n.Name + "(reg, logger),"},
	}}
	if every > 0 {
		c.inserts = append(c.inserts, insertion{"internal/task/task.go", "zen:periodic", n.Name + "Every(),"})
	}
	return c, nil
}

