package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io/fs"
	"maps"
	"os"
	"slices"
	"strings"

	"go.yaml.in/yaml/v3"

	"github.com/dungnh3/kitchen/cmd/kitchen/internal/scaffold"
)

// manifestFile records how a project was generated. "kitchen check" reads
// it.
const manifestFile = ".kitchen.yaml"

// serviceManaged lists the files of a service that kitchen owns: they
// carry managedHeader, "kitchen check" fails when they are edited, and
// "kitchen check -write" updates them to the current template.
var serviceManaged = []string{
	".dockerignore",
	".github/workflows/ci.yml",
	".golangci.yml",
	"Dockerfile",
	"buf.gen.yaml",
}

const managedHeader = `# Managed by kitchen: "kitchen check" fails when this file differs from
# the version kitchen wrote, and "kitchen check -write" updates it to the
# current template. To own the file instead, remove it from "managed" in
# .kitchen.yaml.
`

const manifestHeader = `# Written by kitchen. Keep it in version control: "kitchen check" compares
# the managed files with the hashes below and with the current template.
# Remove a path from "managed" to take ownership of that file.
`

// cliVersion returns the version of this CLI; tests replace it.
var cliVersion = version

// manifest is the content of manifestFile.
type manifest struct {
	// Kitchen is the version of the CLI that last wrote the managed files.
	Kitchen  string         `yaml:"kitchen"`
	Template string         `yaml:"template"`
	Answers  serviceAnswers `yaml:"answers"`
	// Managed maps each managed path to the sha256 of its content.
	Managed map[string]string `yaml:"managed"`
}

// serviceAnswers are the inputs of "kitchen new service" that decide the
// generated content.
type serviceAnswers struct {
	Module         string   `yaml:"module"`
	Name           string   `yaml:"name"`
	Description    string   `yaml:"description"`
	DB             string   `yaml:"db"`
	Auth           string   `yaml:"auth"`
	With           []string `yaml:"with,flow"`
	PubSub         string   `yaml:"pubsub,omitempty"`
	CI             string   `yaml:"ci"`
	CIWorkflow     string   `yaml:"ci_workflow,omitempty"`
	KitchenVersion string   `yaml:"kitchen_version"`
}

func answersOf(p serviceParams) serviceAnswers {
	a := serviceAnswers{
		Module: p.Module, Name: p.Name, Description: p.Description, DB: p.DB, Auth: p.Auth,
		With: slices.Clone(p.With), CI: p.CI, CIWorkflow: p.CIWorkflow, KitchenVersion: p.KitchenVersion,
	}
	if a.With == nil {
		a.With = []string{}
	}
	if p.PubSub() {
		a.PubSub = p.Broker
	}
	return a
}

func (a serviceAnswers) params() serviceParams {
	return serviceParams{
		projectParams: projectParams{
			Module: a.Module, Name: a.Name, Description: a.Description,
			CI: a.CI, CIWorkflow: a.CIWorkflow, KitchenVersion: a.KitchenVersion, Yes: true,
		},
		DB: a.DB, Auth: a.Auth, With: slices.Clone(a.With), Broker: a.PubSub,
	}
}

func hashOf(b []byte) string {
	sum := sha256.Sum256(b)
	return "sha256:" + hex.EncodeToString(sum[:])
}

// addManaged puts managedHeader on the managed files (after a Dockerfile
// syntax directive, which must stay first) and adds manifestFile.
func addManaged(files scaffold.Files, p serviceParams) error {
	m := manifest{Kitchen: cliVersion(), Template: "service", Answers: answersOf(p), Managed: map[string]string{}}
	for _, rel := range serviceManaged {
		b, ok := files[rel]
		if !ok {
			return fmt.Errorf("managed file %s is not in the template", rel)
		}
		b = withHeader(b)
		files[rel] = b
		m.Managed[rel] = hashOf(b)
	}
	b, err := m.marshal()
	if err != nil {
		return err
	}
	files[manifestFile] = b
	return nil
}

func withHeader(b []byte) []byte {
	if bytes.HasPrefix(b, []byte("# syntax=")) {
		first, rest, _ := bytes.Cut(b, []byte("\n"))
		return slices.Concat(first, []byte("\n"+managedHeader), rest)
	}
	return slices.Concat([]byte(managedHeader), b)
}

func (m manifest) marshal() ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString(manifestHeader)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(m); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// errNoManifest reports a directory that kitchen did not generate.
var errNoManifest = errors.New("no " + manifestFile + ": run kitchen check in a project generated by kitchen")

func readManifest(root *os.Root) (manifest, error) {
	var m manifest
	b, err := root.ReadFile(manifestFile)
	if errors.Is(err, fs.ErrNotExist) {
		return m, errNoManifest
	}
	if err != nil {
		return m, err
	}
	dec := yaml.NewDecoder(bytes.NewReader(b))
	dec.KnownFields(true)
	if err := dec.Decode(&m); err != nil {
		return m, fmt.Errorf("%s: %w", manifestFile, err)
	}
	if m.Template != "service" {
		return m, fmt.Errorf("%s: template %q is not supported by kitchen check", manifestFile, m.Template)
	}
	for _, rel := range slices.Sorted(maps.Keys(m.Managed)) {
		if !strings.HasPrefix(m.Managed[rel], "sha256:") {
			return m, fmt.Errorf("%s: managed %s: want a sha256: hash", manifestFile, rel)
		}
	}
	return m, nil
}
